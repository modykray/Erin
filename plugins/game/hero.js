const COOLDOWN_MS = 10000;
const last = new Map();
const handler = async (m) => {
  const now = Date.now();
  const prev = last.get(m.sender) || 0;
  if (now - prev < COOLDOWN_MS) return m.reply(`*⏳ استنى ${Math.ceil((COOLDOWN_MS - (now - prev)) / 1000)} ثانية*`);
  last.set(m.sender, now);
  const [name, powers] = HEROES[Math.floor(Math.random() * HEROES.length)];
  const joke = JOKES[Math.floor(Math.random() * JOKES.length)];
  await m.reply(`*🦸 بطلك النهارده هو: ${name}*\n\n*⚡ قدرات البطل:*\n${powers.map(p => `• ${p}`).join("\n")}\n\n${joke}`);
};
handler.usage = ["بطل"];
handler.category = "games";
handler.command = ["بطل"];
export default handler;
