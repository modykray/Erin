import { writeText } from "../../lib/darwin.js";

const SAFE = "ممنوع: الشتايم، الكلام الجنسي، السخرية من الدين أو الأنبياء أو المقدسات، السياسة، الإساءة لأي شخص أو فئة. لو المشكلة فيها أذى لحد أو حاجة غير قانونية، ما تساعدش فيها واقترح بديل آمن.";
const SYS = `أنت مستشار مصري عملي وواقعي وخفيف الدم. المستخدم هيحكيلك مشكلة من حياته اليومية. اقترح من 3 إلى 5 حلول عملية مرتبة من الأفضل للأقل، كل حل في سطر مرقم (1. 2. 3.) وبخطوات قصيرة وواضحة، بالعامية المصرية. افتتح بجملة قصيرة تتعاطف بيها، ولو في معلومة ناقصة قول إيه هو الافتراض. الإجمالي أقل من 800 حرف. لو المشكلة صحية أو قانونية أو مالية كبيرة، قول في آخر سطر إن ده رأي عام ولازم يستشير دكتور أو محامي أو متخصص. ${SAFE}`;
const SELF_HARM = /(انتحر|اقتل نفسي|أقتل نفسي|اموت نفسي|عايز اموت|عايز أموت|اذي نفسي|أذي نفسي|ايذاء نفسي|اخلص على نفسي)/;
const SENSITIVE = /(مرض|دكتور|الم |ألم|علاج|دوا|دواء|حامل|حمل|سرطان|قضية|محامي|محكمه|محكمة|قانون|طلاق|نفقة|شرطة|بلاغ|ديون|دين |سلف|قرض)/;
const COOLDOWN_MS = 15000;
const last = new Map();

const handler = async (m, { text }) => {
  const now = Date.now();
  const prev = last.get(m.sender) || 0;
  if (now - prev < COOLDOWN_MS) return m.reply(`*⏳ استنى ${Math.ceil((COOLDOWN_MS - (now - prev)) / 1000)} ثانية*`);
  const q = (text || "").trim().replace(/^(مشكلتي|مشكلة|مشكله)\s*/, "").slice(0, 500);
  if (!q) return m.reply("*🛠️ احكيلي مشكلتك بعد الأمر، مثلا:*\n.مشكلة مش بعرف أصحى بدري\n.حل مشكلتي صاحبي بيتأخر عليا دايما");
  if (SELF_HARM.test(q)) {
    return m.reply("*💛 كلامك مهم وأنا مهتم بيك.* لو بتفكر تأذي نفسك، كلم حد قريب منك دلوقتي (حد من أهلك أو صاحب تثق فيه)، ولو حاسس بخطر فوري اتصل بالإسعاف 123 أو روح أقرب مستشفى. مش لازم تشيل ده لوحدك. وأنا موجود لو عايز تحكي 🐦");
  }
  last.set(m.sender, now);
  let out = "";
  try { out = (await writeText(SYS, "المشكلة: " + q, "")).trim().slice(0, 1200); } catch (e) { console.log("[PROBLEM] ai error:", e?.message); }
  if (!out) return m.reply("*😅 مخي هنج دلوقتي، ابعت المشكلة تاني بعد شوية*");
  const note = SENSITIVE.test(q) && !/(دكتور|محامي|متخصص)/.test(out.slice(-120)) ? "\n\n⚠️ ده رأي عام ومش بديل عن دكتور أو محامي أو متخصص." : "";
  await m.reply(`*🛠️ حلول لمشكلتك:*\n\n${out}${note}`);
};
handler.usage = ["مشكلة", "حل مشكلتي"];
handler.category = "games";
handler.command = ["مشكلة", "مشكله", "حل", "حل_مشكلتي"];
export default handler;
